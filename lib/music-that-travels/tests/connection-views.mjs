import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../source/geography.html',import.meta.url),'utf8');
const script=html.split('<script>')[1].split('</script>')[0];
new Function(script);
const nodes=new Map();
const node=id=>{if(!nodes.has(id))nodes.set(id,{classes:new Set(),attrs:{},classList:{toggle(name,on){on?nodes.get(id).classes.add(name):nodes.get(id).classes.delete(name)}},setAttribute(k,v){this.attrs[k]=v}});return nodes.get(id)};
let paints=0,restores=0;
const context=vm.createContext({$:node,render:()=>paints++,restoreOverview:()=>restores++});
const views=script.slice(script.indexOf('let coversVisible='),script.indexOf("let renderedUIKey='';"));
vm.runInContext("let selected=null,overviewPaint={};"+views,context);
const run=s=>vm.runInContext(s,context);
run('updateConnectionViews()');assert.equal(node('isolateSelection').disabled,true);
run("setConnectionView('covers');updateConnectionViews()");
assert.ok(node('map').classes.has('connections-only'));
assert.equal(node('toggleCovers').attrs['aria-label'],'Show covers');
assert.equal(node('toggleCovers').attrs['aria-pressed'],'true');
run("setConnectionView('isolate');updateConnectionViews()");assert.equal(run('isolateSelection'),false,'no empty isolated view without a record');
run("selected='123';setConnectionView('isolate');updateConnectionViews()");
assert.ok(node('map').classes.has('isolated-selection'));
assert.equal(node('isolateSelection').disabled,false);
run("setConnectionView('covers');updateConnectionViews()");
assert.equal(node('map').classes.has('connections-only'),false);
assert.ok(node('map').classes.has('isolated-selection'),'cover visibility and isolation are independent');
run("selected='456';updateConnectionViews()");assert.ok(node('map').classes.has('isolated-selection'),'changing selected record retains isolation');
run("selected=null;updateConnectionViews()");assert.equal(node('map').classes.has('isolated-selection'),false);
assert.equal(node('isolateSelection').disabled,true);
assert.equal(run('overviewPaint'),null,'view changes invalidate composited camera backdrop');
assert.ok(paints>0&&restores===paints);
assert.ok(html.includes('#map.connections-only #markers,#map.connections-only #traveler'));
assert.ok(html.includes('#map.isolated-selection #markers,#map.isolated-selection #mapLabels,#map.isolated-selection #listeningJourney'));
assert.ok(script.includes('placement.x=placement.ax;placement.y=placement.ay;placement.size=0'),'hidden-cover threads anchor at actual geographic point');
assert.ok(script.includes('function reset(){coversVisible=true;isolateSelection=false;'));
assert.ok(script.includes("$('clearAndReset').onclick=reset"));
assert.ok(html.includes('aria-label="Clear selection and reset view"'));
assert.ok(!views.includes('.textContent='),'updating accessible labels preserves icon markup');
console.log('Connection views: independent cover visibility, selected-only isolation, changing selection, empty selection, geographic anchors and reset verified.');
